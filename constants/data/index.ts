export type Position = 'GK' | 'DEF' | 'MF' | 'FW';

export interface Player {
  n: number;
  name: string;
  pos: Position;
  isFoil?: boolean;
  alias?: string; // code Panini original pour les stickers spéciaux
}

export interface Team {
  code: string;
  name: string;
  flag: string;
  colors: [string, string, string];
  players: Player[];
}

// 18 joueurs : p[0..10] → n=2..12 | p[11..17] → n=14..20
// n=1 = emblème (foil), n=13 = photo d'équipe (auto)
type P = [string, Position];
function sq(teamName: string, p: P[]): Player[] {
  const r: Player[] = [{ n: 1, name: `${teamName} — Emblème`, pos: 'GK', isFoil: true }];
  for (let i = 0; i < 11; i++) r.push({ n: i + 2, name: p[i][0], pos: p[i][1] });
  r.push({ n: 13, name: "Photo d'équipe", pos: 'GK' });
  for (let i = 11; i < 18; i++) r.push({ n: i + 3, name: p[i][0], pos: p[i][1] });
  return r;
}

